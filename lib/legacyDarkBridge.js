/**
 * lib/legacyDarkBridge.js
 *
 * Dark-mode bridge for older pages that use Tailwind palette tints
 * (bg-amber-50, border-indigo-200, text-rose-800 …) without a `dark:` variant.
 * In dark mode those stay light-on-light or dark-on-dark and become unreadable.
 *
 * Every rule is wrapped in :where() so its specificity stays low:
 *  - it beats the plain utility (.bg-amber-50) because of the theme prefix,
 *  - but any explicit `dark:` variant on the element still wins.
 * Light mode is untouched.
 */

const HUES = {
  red: ["239,68,68", "#FCA5A5"],
  orange: ["249,115,22", "#FDBA74"],
  amber: ["245,158,11", "#FCD34D"],
  yellow: ["234,179,8", "#FDE047"],
  lime: ["132,204,22", "#BEF264"],
  green: ["34,197,94", "#86EFAC"],
  emerald: ["16,185,129", "#6EE7B7"],
  teal: ["20,184,166", "#5EEAD4"],
  cyan: ["6,182,212", "#67E8F9"],
  sky: ["14,165,233", "#7DD3FC"],
  blue: ["59,130,246", "#93C5FD"],
  indigo: ["99,102,241", "#A5B4FC"],
  violet: ["139,92,246", "#C4B5FD"],
  purple: ["168,85,247", "#D8B4FE"],
  fuchsia: ["217,70,239", "#F0ABFC"],
  pink: ["236,72,153", "#F9A8D4"],
  rose: ["244,63,94", "#FDA4AF"],
};
const NEUTRALS = ["slate", "gray", "zinc", "neutral", "stone"];

/** class token, with or without an opacity suffix (bg-amber-50 / bg-amber-50/60) */
const cls = (c, used) =>
  [used.has(c) && `[class~="${c}"]`, [...used].some((u) => u.startsWith(c + "/")) && `[class*="${c}/"]`]
    .filter(Boolean)
    .join(",");

/** Elements that also carry a solid mid-tone background (bg-amber-400 …) keep their dark text — neutrals included (amber CTA with text-slate-900). */
// Only real solid backgrounds count: matching any "-300" token also caught border-amber-300,
// which left text-amber-950 dark on a dark tint.
const solidBg = (used) =>
  [...Object.keys(HUES), ...NEUTRALS]
    .flatMap((h) => [300, 400, 500].map((n) => `bg-${h}-${n}`))
    .map((c) => cls(c, used))
    .filter(Boolean)
    .join(",") || '[class~="bg-none-solid"]';

function rules(used) {
  const out = [];
  const SOLID_BG = solidBg(used);
  const add = (tokens, body) => {
    const sel = tokens.map((t) => cls(t, used)).filter(Boolean).join(",");
    if (sel) out.push(body(sel));
  };
  for (const [h, [rgb, light]] of Object.entries(HUES)) {
    add([`bg-${h}-50`, `bg-${h}-100`, `bg-${h}-200`], (s) => `:where(${s}){background-color:rgba(${rgb},.12)}`);
    add([`border-${h}-100`, `border-${h}-200`, `border-${h}-300`], (s) => `:where(${s}){border-color:rgba(${rgb},.35)}`);
    add([6, 7, 8, 9].map((n) => `text-${h}-${n}00`).concat(`text-${h}-950`), (s) => `:where(:is(${s}):not(${SOLID_BG})){color:${light}}`);
    add([`from-${h}-50`, `from-${h}-100`], (s) => `:where(${s}){--tw-gradient-from:rgba(${rgb},.14) var(--tw-gradient-from-position);--tw-gradient-to:rgba(${rgb},0) var(--tw-gradient-to-position);--tw-gradient-stops:var(--tw-gradient-from),var(--tw-gradient-to)}`);
    add([`to-${h}-50`, `to-${h}-100`], (s) => `:where(${s}){--tw-gradient-to:rgba(${rgb},.06) var(--tw-gradient-to-position)}`);
  }
  for (const h of NEUTRALS) {
    add([`bg-${h}-50`, `bg-${h}-100`, `bg-${h}-200`], (s) => `:where(${s}){background-color:rgba(255,255,255,.05)}`);
    add([`border-${h}-100`, `border-${h}-200`, `border-${h}-300`], (s) => `:where(${s}){border-color:var(--border,#2A2A2A)}`);
    add([`text-${h}-600`, `text-${h}-700`], (s) => `:where(:is(${s}):not(${SOLID_BG})){color:var(--text-2,#B5B5B0)}`);
    add([`text-${h}-800`, `text-${h}-900`, `text-${h}-950`], (s) => `:where(:is(${s}):not(${SOLID_BG})){color:var(--text,#F5F5F2)}`);
  }
  return out;
}

/** Build the stylesheet for the set of palette classes the codebase actually uses. */
export function buildLegacyDarkCss(usedClasses) {
  const body = rules(new Set(usedClasses));
  return (
    "/* GENERATED by scripts/gen-legacy-dark-css.mjs from lib/legacyDarkBridge.js. Do not edit by hand. */\n" +
    "@media (prefers-color-scheme: dark){\n" +
    body.map((r) => `:root:not([data-theme="light"]) ${r}`).join("\n") +
    "\n}\n" +
    body.map((r) => `:root[data-theme="dark"] ${r}`).join("\n") +
    "\n"
  );
}

/** Palette classes (with optional /opacity) found in source text. */
export const PALETTE_CLASS_RE =
  /\b(?:bg|text|border|from|to)-(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3}(?:\/\d+)?\b/g;
