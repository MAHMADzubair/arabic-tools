#!/usr/bin/env node
/**
 * Regenerates lib/pageDates.generated.js from git history.
 * For each indexed tool route, records the date of the last commit that
 * touched its page file. Run before release:  node scripts/update-page-dates.mjs
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const sitemap = readFileSync("app/sitemap.js", "utf8");
const routes = [...new Set([...sitemap.matchAll(/"(\/[a-z0-9\-/]+)"/g)].map((m) => m[1]))].sort();
const NON_TOOL = new Set(["/about", "/contact", "/changelog", "/privacy", "/terms", "/disclaimer", "/ar/sa", "/ar/ae"]);

const dates = {};
for (const route of routes) {
  if (NON_TOOL.has(route)) continue;
  const file = `app${route}/page.js`;
  if (!existsSync(file)) continue;
  const date = execFileSync("git", ["log", "-1", "--format=%ad", "--date=short", "--", file], { encoding: "utf8" }).trim();
  if (date) dates[route] = date;
}

const body = `// AUTO-GENERATED by scripts/update-page-dates.mjs — do not edit by hand.
// Date of the last commit that changed each tool page file.
export const PAGE_UPDATED = ${JSON.stringify(dates, null, 2)};
`;
writeFileSync("lib/pageDates.generated.js", body);
console.log(`Wrote ${Object.keys(dates).length} routes to lib/pageDates.generated.js`);
